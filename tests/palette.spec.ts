import {test,expect} from './fixtures/ownedProject';
test('typed components survive saves, snapshots and zoomed canvas drops',async({page,browser,ownedProject},testInfo)=>{
  test.setTimeout(75000);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('/');await page.getByRole('tab',{name:'Editor',exact:true}).click();
  await page.getByRole('button',{name:'Add Database',exact:true}).click();
  await expect(page.locator('#node-kind')).toHaveValue('database');await expect(page.locator('#label')).toHaveValue('Database 2');
  await page.locator('#save-online').click();await expect(page.locator('#save-state')).toHaveText('Saved Online');
  let saved=await ownedProject.api('/projects/'+ownedProject.draft.id);
  expect(saved.document.nodes.find((n:any)=>n.label==='Database 2').type).toBe('database');
  await page.getByRole('button',{name:'Reset Zoom',exact:true}).click();
  await page.getByRole('button',{name:'Zoom In',exact:true}).click();
  await expect(page.getByRole('button',{name:'Reset Zoom',exact:true})).toHaveText('110%');
  const stage=await page.getByLabel('Diagram Viewport',{exact:true}).boundingBox();
  await page.mouse.move(stage!.x+8,stage!.y+8);await page.mouse.down();await page.mouse.move(stage!.x+48,stage!.y+38);await page.mouse.up();
  const source=page.getByRole('button',{name:'Add Cache',exact:true});const target=page.locator('.diagram-plane');
  const bounds=await target.boundingBox();expect(bounds).toBeTruthy();
  await source.dragTo(target,{targetPosition:{x:bounds!.width*.6,y:bounds!.height*.6}});
  await expect(page.locator('#node-kind')).toHaveValue('cache');
  await expect(page.getByRole('button',{name:'Cache',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Undo',exact:true}).click();await expect(page.getByRole('button',{name:'Cache',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Redo',exact:true}).click();await expect(page.getByRole('button',{name:'Cache',exact:true})).toBeVisible();
  await page.locator('#save-online').click();await expect(page.locator('#save-state')).toHaveText('Saved Online');
  saved=await ownedProject.api('/projects/'+ownedProject.draft.id);const cache=saved.document.nodes.find((n:any)=>n.type==='cache');
  expect(cache.x).toBeCloseTo(60,0);expect(cache.y).toBeCloseTo(60,0);
  await page.reload();await page.getByRole('tab',{name:'Editor',exact:true}).click();
  await page.getByRole('button',{name:'Cache',exact:true}).click();await expect(page.locator('#node-kind')).toHaveValue('cache');
  const publication=await ownedProject.api(`/projects/${saved.id}/publications`,'POST',{version:saved.version},201);
  const snapshot=await ownedProject.api('/publications/'+publication.id);expect(snapshot.document.nodes.find((n:any)=>n.type==='cache')).toBeTruthy();
  const guest=await browser.newContext({baseURL:testInfo.project.use.baseURL});
  await guest.route(/^https:\/\/fonts\.(?:googleapis|gstatic)\.com\//,route=>route.abort());
  try{
    const reader=await guest.newPage();await reader.goto('/p/'+publication.id);
    await expect(reader.locator('.node-type.cache')).toBeVisible();
    await expect(reader.getByRole('button',{name:'Add Cache',exact:true})).toHaveCount(0);
    await reader.locator('#remix').click();await reader.waitForURL('**/?remix=1');
    await reader.getByRole('tab',{name:'Editor',exact:true}).click();await reader.getByRole('button',{name:'Cache',exact:true}).click();
    await expect(reader.locator('#node-kind')).toHaveValue('cache');
  }finally{await guest.close();}
  await page.setViewportSize({width:1440,height:1000});await page.screenshot({path:'.runtime/palette-desktop.png'});
  await page.setViewportSize({width:390,height:844});await page.getByRole('button',{name:'Open Inspector',exact:true}).click();
  await page.getByRole('button',{name:'Add Queue',exact:true}).click();await expect(page.locator('#node-kind')).toHaveValue('queue');
  await page.locator('.inspector-content').evaluate(element=>{element.scrollTop=0;});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'.runtime/palette-mobile.png'});
  await page.getByRole('button',{name:'Close Inspector',exact:true}).click();
  await page.locator('#theme-toggle').click();await page.getByRole('button',{name:'Open Inspector',exact:true}).click();
  await page.screenshot({path:'.runtime/palette-mobile-dark.png'});
  testInfo.annotations.push({type:'scope',description:'Palette changes are not auto-appended to scenario steps; authors choose their route explicitly.'});
});
