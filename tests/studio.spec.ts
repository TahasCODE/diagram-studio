import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
import { examples } from '../src/lib/examples';
async function signInAfterRegistration(page: Page,password: string) {
  await expect(page.getByText('Account created successfully.',{exact:false})).toBeVisible();
  expect((await (await page.request.get('/api/auth/me')).json()).user).toBeNull();
  await page.getByLabel('Password',{exact:true}).fill('IncorrectPassword123');
  await page.getByRole('dialog').getByRole('button',{name:'Sign In',exact:true}).click();
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('Email or password is incorrect');
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.evaluate(() => {
    (window as Window & {authLoadingSeen?:boolean}).authLoadingSeen=false;
    const observer=new MutationObserver(()=>{if(document.querySelector('form[aria-busy="true"]'))(window as Window & {authLoadingSeen?:boolean}).authLoadingSeen=true;});
    observer.observe(document.body,{subtree:true,attributes:true,childList:true});
  });
  await page.getByRole('dialog').getByRole('button',{name:'Sign In',exact:true}).click();
  await expect(page.getByRole('heading',{name:'You’re Signed In'})).toBeVisible();
  expect(await page.evaluate(()=>(window as Window & {authLoadingSeen?:boolean}).authLoadingSeen)).toBe(true);
  await page.screenshot({path:'.runtime/auth-success.png'});
  await page.getByRole('button',{name:'Continue to Workspace'}).click();
}

test('migrates a prototype project and preserves editing, review, history, import and export', async ({page}) => {
  await page.addInitScript(document => localStorage.setItem('diagram-studio-v1',JSON.stringify(document)), {...examples.refund,title:'Existing Prototype Project'});
  const errors: string[] = []; page.on('pageerror',error => errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('#project-heading')).toHaveText('Existing Prototype Project');
  await page.getByRole('tab',{name:'Editor',exact:true}).click();
  await page.locator('#label').fill('Start Refund');
  await page.locator('#label').press('Tab');
  await expect(page.locator('.node').first()).toHaveText('Start Refund');
  await expect(page.locator('#reviews')).toContainText('Renamed');
  await page.locator('#undo').click(); await expect(page.locator('.node').first()).toHaveText('Request refund');
  await page.locator('#redo').click(); await expect(page.locator('.node').first()).toHaveText('Start Refund');
  await page.locator('#duplicate-scenario').click();
  await expect(page.locator('#scenario')).toHaveValue('3');
  const node = page.getByRole('button',{name:'Review request',exact:true});
  const bounds = await node.boundingBox();
  await page.mouse.move(bounds!.x+bounds!.width/2,bounds!.y+bounds!.height/2);
  await page.mouse.down(); await page.mouse.move(bounds!.x+bounds!.width/2+45,bounds!.y+bounds!.height/2-30,{steps:8}); await page.mouse.up();
  await page.locator('#undo').click();
  await page.getByRole('tab',{name:'Playback',exact:true}).click();
  await page.locator('#next').click(); await expect(page.locator('#progress')).toHaveAttribute('value','2');
  await page.locator('#restart').click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('tab',{name:'Project',exact:true}).click();
  await page.locator('#export-project').click();
  expect((await downloadPromise).suggestedFilename()).toBe('diagram-studio-project.json');
  await page.locator('#project-file').setInputFiles({name:'legacy.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(examples.checkout))});
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await expect(page.locator('#project-heading')).toHaveText('Checkout and Payment');
  await page.locator('#undo').click();
  await expect(page.locator('#project-heading')).toHaveText('Existing Prototype Project');
  expect(errors).toEqual([]);
});

